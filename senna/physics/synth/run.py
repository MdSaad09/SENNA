"""The F03 synthetic-2026 battery — transform, assemble, write transforms.yaml.

Stages run in dependency order: T2's corner exponent feeds T1's corner-exit
speeds; T1's profile feeds T4's energy budget and c_lc; T3/T6 supply the mass
delta; assembly composes the 2026 base pace under the real-beats-transform-
beats-donor rule; T7 and T8 close it out. F02's real-data fits are read from
physics_params.yaml, never recomputed — this battery owns transforms.yaml and
nothing else (physics_params.yaml stays F02's).

Run it: python -m senna.physics.synth.run   (or `make synth`)
"""

