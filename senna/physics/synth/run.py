log = logging.getLogger(__name__)

MODULES = ("aero", "pointmass", "energy", "mass_fuel", "overtaking", "residual")
SLICKS = ("SOFT", "MEDIUM", "HARD")

TRANSFORMS_HEADER = (
    "# SENNA — 2026 transforms (F03). Generated by senna.physics.synth.run;\n"
    "# edit the transforms or configs/synth.yaml, never this file by hand.\n"
)
POINTMASS_NB = "fitted: notebooks/fit_point_mass.ipynb"
AERO_NB = "fitted: notebooks/fit_corner_exponent.ipynb"
ENERGY_NB = "fitted: notebooks/fit_energy_budget.ipynb"
OVERTAKE_NB = "fitted: notebooks/fit_overtaking.ipynb"
RESIDUAL_NB = "fitted: notebooks/fit_residual_2026.ipynb"


async def run_battery(args: argparse.Namespace) -> dict:
    synth_cfg = config.load("synth")
    ingest_cfg = config.load("ingest")
    split = config.load("data_split")
    physics_2026 = config.load("physics_2026")
    circuits_cfg = config.load("circuits")
    params = config.load("physics_params")
    calibration_rounds = config.get(split, "calibration_rounds")

    only = set(args.only.split(",")) if args.only else set(MODULES)
    unknown = only - set(MODULES)
    if unknown:
        raise SystemExit(f"unknown --only module(s): {', '.join(sorted(unknown))}")

    from senna.data import fastf1_loader

    fastf1_loader.enable_cache(config.REPO_ROOT / config.get(ingest_cfg, "fastf1.cache_dir"))

    engine = engine_for(database_url())
    try:
        async with engine.connect() as conn:
            index = await fit_frames.circuit_index(conn, calibration_rounds)
            if args.circuit:
                index = index[index["slug"] == args.circuit]
                if index.empty:
                    raise SystemExit(f"no ingested sessions for circuit '{args.circuit}'")
            battery = _Battery(index, synth_cfg, ingest_cfg, physics_2026, circuits_cfg, params,
                               calibration_rounds)
            for module in MODULES:  # declaration order is dependency order
                if module in only:
                    await battery.run(module, conn, fastf1_loader)
    finally:
        await engine.dispose()

    transforms = battery.transforms()
    if args.only or args.circuit:
        log.info("narrowed run (--only/--circuit): transforms.yaml not written")
        return transforms
    validate_complete(transforms)
    args.transforms_out.write_text(
        render_params(transforms, generated_at=battery.data_through(), header=TRANSFORMS_HEADER)
    )
    log.info("wrote %s", args.transforms_out)
    battery.write_physics_2026_fitted(args.physics_2026_out)
    return transforms


class _Battery:
    def __init__(self, index, synth_cfg, ingest_cfg, physics_2026, circuits_cfg, params, rounds):
        self.index = index
        self.synth_cfg = synth_cfg
        self.ingest_cfg = ingest_cfg
        self.physics_2026 = physics_2026
        self.circuits_cfg = circuits_cfg
        self.params = params
        self.calibration_rounds = rounds
        self.taper_2026 = {
            "mgu_k_max_kw": self._p26("power_unit.mgu_k_max_kw"),
            "full_power_to_kmh": self._p26("power_unit.deploy_taper.full_power_to_kmh"),
            "zero_power_at_kmh": self._p26("power_unit.deploy_taper.zero_power_at_kmh"),
        }
        self.exponent = None
        self.apex_pairs = pd.DataFrame(columns=["circuit", "v_2024_kmh", "v_2026_kmh"])
        self.effective: dict[str, pointmass.EffectiveCar] = {}
        self.t1: dict[str, dict] = {}
        self.t4: dict[str, dict] = {}
        self.t3: dict[str, dict] = {}
        self.overtake = None
        self.residual: dict[str, float] = {}
        self.c_global = None

    async def run(self, module: str, conn, loader) -> None:
        await getattr(self, f"_run_{module}")(conn, loader)

    def _slugs(self) -> list[str]:
        return sorted(self.index["slug"].unique())

    def _event(self, slug: str, era: str):
        rows = self.index[(self.index["slug"] == slug) & (self.index["era"] == era)
                          & (self.index["session_name"] == "Race")]
        return None if rows.empty else rows.iloc[0]

    def data_through(self) -> str:
        last_season = int(self.index["season"].max())
        last_round = int(self.index.loc[self.index["season"] == last_season, "round"].max())
        return f"seasons {int(self.index['season'].min())}-{last_season}, round {last_round}"

    async def _run_aero(self, conn, loader) -> None:
        throttle_full = self._throttle_full_pct()
        min_apex = float(config.get(self.synth_cfg, "aero.min_corner_apex_kmh"))
        pairs = []
        for slug in self._slugs():
            trace_2024 = _representative_trace(self._event(slug, "2024"), loader)
            trace_2026 = _representative_trace(self._event(slug, "2026"), loader)
            if trace_2024 is None or trace_2026 is None:
                continue
            apex_2024 = aero.apex_speeds_kmh(trace_2024, throttle_full_pct=throttle_full)
            apex_2026 = aero.apex_speeds_kmh(trace_2026, throttle_full_pct=throttle_full)
            matched = aero.matched_apexes(
                apex_2024, apex_2026, circuit=slug, min_corner_apex_kmh=min_apex
            )
            if not matched.empty:
                pairs.append(matched)
        self.apex_pairs = pd.concat(pairs, ignore_index=True) if pairs else self.apex_pairs
        fit = aero.fit_corner_exponent(
            self.apex_pairs,
            downforce_ratio=float(config.get(self.physics_2026, "aero.downforce_vs_2024")),
            prior=float(config.get(self.synth_cfg, "aero.exponent_prior")),
            bounds=tuple(config.get(self.synth_cfg, "aero.exponent_bounds")),
            min_corners=int(config.get(self.synth_cfg, "aero.min_corners")),
        )
        self.exponent = fit
        log.info("aero: corner exponent=%.3f over %d corners (fallback=%s)",
                 fit.exponent, fit.n_corners, fit.fallback)

    async def _run_pointmass(self, conn, loader) -> None:
        if self.exponent is None:
            raise SystemExit("pointmass needs aero (the corner exponent) in the same run")
        throttle_full = self._throttle_full_pct()
        physics_2024 = config.load("physics_2024")
        car_2024 = float(config.get(physics_2024, "mass.minimum_car_kg"))
        fuel_2024 = float(config.get(physics_2024, "mass.race_fuel_kg"))
        drag_2026 = self._p26("aero.drag_vs_2024_x_mode")
        p_ice_2026 = self._p26("power_unit.ice_max_kw")
        downforce = self._p26("aero.downforce_vs_2024")
        ref_frac = float(config.get(self.synth_cfg, "pointmass.reference_fuel_frac"))
        smooth = float(config.get(self.synth_cfg, "pointmass.accel_smooth_window_s"))
        tol = float(config.get(self.synth_cfg, "pointmass.profile_tolerance_frac"))
        for slug in self._slugs():
            trace = _representative_trace(self._event(slug, "2024"), loader)
            if trace is None:
                continue
            mass_2024 = car_2024 + ref_frac * fuel_2024
            car = pointmass.fit_effective_car(
                trace, mass_kg=mass_2024, throttle_full_pct=throttle_full,
                accel_smooth_window_s=smooth, profile_tolerance_frac=tol,
            )
            self.effective[slug] = car
            mass_2026 = self._reference_mass_2026_kg()
            self.t1[slug] = _profile_2026(
                trace, car, exponent=self.exponent.exponent, taper=self.taper_2026,
                p_ice_2026=p_ice_2026, drag_scale=drag_2026, mass_2026=mass_2026,
                downforce_ratio=downforce, throttle_full_pct=throttle_full,
            )
            log.info("pointmass %s: full_throttle=%.1fs e_dep=%.2fMJ delta_lap=%.2fs ok=%s",
                     slug, self.t1[slug]["full_throttle_s"], self.t1[slug]["e_dep_mj"],
                     self.t1[slug]["delta_lap_s"], car.ok)

    async def _run_energy(self, conn, loader) -> None:
        clipping_kw = self._p26("harvest.super_clipping_kw")
        lift_kw = self._p26("harvest.lift_and_coast_kw")
        drag_scale = self._p26("aero.drag_vs_2024_x_mode")
        p_ice = self._p26("power_unit.ice_max_kw")
        sweep = int(config.get(self.synth_cfg, "energy_budget.lc_sweep_points"))
        mass_2026 = self._reference_mass_2026_kg()
        for slug, profile in self.t1.items():
            h_max = _circuit_h_max(self.circuits_cfg, slug)
            braking = _param(self.params, slug, "energy", "2024", "braking_energy_mj_per_lap")
            budget = energy_budget.energy_budget(
                h_max_mj=h_max, e_dep_mj=profile["e_dep_mj"],
                braking_energy_mj=float(braking) if braking is not None else 0.0,
                full_throttle_s=profile["full_throttle_s"], super_clipping_kw=clipping_kw,
            )
            c_lc = energy_budget.c_lc_s_per_mj(
                profile["top_speed_kmh"], mass_kg=mass_2026, p_base_kw=p_ice,
                beta_drag=self.effective[slug].beta_drag * drag_scale,
                taper=self.taper_2026, lift_kw=lift_kw, sweep_points=sweep,
            )
            c_atk, p_der = self._attack_and_derate(profile["longest_straight"], mass_2026, p_ice)
            self.t4[slug] = {
                "budget": budget, "c_lc_s_per_mj": c_lc, "c_atk_s": c_atk, "p_der_s_per_mj": p_der,
            }

    def _attack_and_derate(self, straight, mass_kg, p_ice_kw):
        """Override time gain (c_atk) and derate cost per MJ (p_der) on the longest straight.

        c_atk: Manual Override holds 350 kW to 337 km/h (AR-03) instead of tapering
        from 290, so the same straight is quicker. p_der: with no deploy the straight
        loses time; the ratio of that loss to the MGU-K energy foregone is the
        shortfall penalty (5.5.3). Both fall out of the T1 integrator — nearly free.
        """
        if straight is None:
            return None, None
        override_taper = dict(
            self.taper_2026, full_power_to_kmh=self._p26("power_unit.manual_override.held_to_kmh")
        )
        zero_taper = dict(self.taper_2026, mgu_k_max_kw=0.0)
        v0, dist = straight["v0_kmh"], straight["dist_m"]
        kwargs = dict(mass_kg=mass_kg, p_base_kw=p_ice_kw, beta_drag=straight["beta_2026"])
        normal = pointmass.run_straight(v0, dist, taper=self.taper_2026, **kwargs)
        override = pointmass.run_straight(v0, dist, taper=override_taper, **kwargs)
        no_deploy = pointmass.run_straight(v0, dist, taper=zero_taper, **kwargs)
        c_atk = normal.time_s - override.time_s
        gain_s = no_deploy.time_s - normal.time_s
        p_der = gain_s / normal.e_dep_mj if normal.e_dep_mj > 0 else None
        return c_atk, p_der

    async def _run_mass_fuel(self, conn, loader) -> None:
        physics_2024 = config.load("physics_2024")
        fuel_2026 = self._p26("mass.race_fuel_kg")
        fuel_2024 = float(config.get(physics_2024, "mass.race_fuel_kg"))
        # AR-09: the -30 kg minimum-mass change, derived from the two era configs
        # rather than restated, so it can never drift from them
        car_delta = self._p26("mass.minimum_car_kg") - float(
            config.get(physics_2024, "mass.minimum_car_kg")
        )
        pooled_k_m = float(config.get(self.params, "globals.k_m_pooled_s_per_kg_2026"))
        for slug in self.t1:
            k_m = _param(self.params, slug, "joint_pace", "2026", "k_m_s_per_kg")
            if k_m is None:
                k_m = _param(self.params, slug, "joint_pace", "2024", "k_m_s_per_kg")
            k_m = pooled_k_m if k_m is None else float(k_m)
            # both eras run their allowance to the flag, so the average-load
            # delta is half the allowance change (T3 through k_m only, E-10)
            fuel_delta = 0.5 * (fuel_2026 - fuel_2024)
            self.t3[slug] = {
                "k_m_s_per_kg": k_m,
                "static_mass_delta_s": mass_fuel.static_mass_delta_s(
                    k_m_s_per_kg=k_m, car_delta_kg=car_delta, fuel_delta_kg=fuel_delta
                ),
                "avg_fuel_kg_2026": 0.5 * fuel_2026,
            }

    async def _run_overtaking(self, conn, loader) -> None:
        detection_gap = self._p26("power_unit.manual_override.detection_gap_s")
        pace_window = int(config.get(self.synth_cfg, "overtaking.pace_window_laps"))
        restart_exclude = int(config.get(self.synth_cfg, "overtaking.restart_exclude_laps"))
        retire_lookahead = int(config.get(self.synth_cfg, "overtaking.retire_lookahead_laps"))
        events = []
        for era in ("2024", "2026"):
            laps = await frames.position_laps(conn, era, self.calibration_rounds)
            if laps.empty:
                continue
            extracted = overtaking.extract_pass_events(
                laps, detection_gap_s=detection_gap, pace_window_laps=pace_window,
                restart_exclude_laps=restart_exclude, retire_lookahead_laps=retire_lookahead,
            )
            events.append(extracted.events)
            log.info("overtaking %s: %d events, excluded=%s", era, len(extracted.events),
                     extracted.n_excluded)
        all_events = pd.concat(events, ignore_index=True) if events else pd.DataFrame()
        if not all_events.empty:
            self.overtake = overtaking.fit_overtaking(
                all_events, calibration_rounds=self.calibration_rounds
            )
            log.info("overtaking: beta_pace=%.3f shift_2026=%.3f n=%d",
                     self.overtake.beta_pace, self.overtake.shift_2026, self.overtake.n_events)

    async def _run_residual(self, conn, loader) -> None:
        real_laps = await frames.position_laps(conn, "2026", self.calibration_rounds)
        for slug in self._slugs():
            real_t0 = _param(self.params, slug, "joint_pace", "2026", "t0_s")
            transform_t0 = self._transform_t0(slug)
            if real_t0 is None or transform_t0 is None:
                continue  # need both a real fit to check against and a transform to score
            circuit_laps = real_laps[real_laps["session_id"].isin(self._session_ids(slug))]
            if circuit_laps.empty:
                continue
            clean = circuit_laps[
                circuit_laps["is_green"].fillna(False).astype(bool)
                & circuit_laps["is_accurate"].fillna(False).astype(bool)
            ]
            # the model-implied median is the transform intercept carrying the
            # circuit's own race offset; c_circuit then isolates the transform's
            # t0 error (real_t0 - transform_t0), the leftover T8 absorbs
            race_offset = float(np.median(clean["lap_time_s"])) - float(real_t0)
            model_median = transform_t0 + race_offset
            self.residual[slug] = fit_residual_s(
                circuit_laps, model_median, calibration_rounds=self.calibration_rounds
            )
        if self.residual:
            self.c_global = pool_residual_s(self.residual)
            log.info("residual: %d circuits, c_global=%.3fs", len(self.residual), self.c_global)

    def _p26(self, dotted: str) -> float:
        return float(config.get(self.physics_2026, dotted))

    def _reference_mass_2026_kg(self) -> float:
        """2026 car at the reference fuel load T1 integrates at (AR-09, AR-10)."""
        ref_frac = float(config.get(self.synth_cfg, "pointmass.reference_fuel_frac"))
        return self._p26("mass.minimum_car_kg") + ref_frac * self._p26("mass.race_fuel_kg")

    def _throttle_full_pct(self) -> float:
        # the telemetry full-throttle threshold is an ingest/fits concern; reuse
        # F02's single source rather than duplicating the constant (AR-16)
        return float(config.get(config.load("fits"), "energy.throttle_full_pct"))

    def _session_ids(self, slug: str) -> set[int]:
        rows = self.index[(self.index["slug"] == slug) & (self.index["era"] == "2026")]
        return set(int(s) for s in rows["session_id"])

    def _transform_t0(self, slug: str) -> float | None:
        """The T1+T2+T3 predicted 2026 intercept, independent of any real fit."""
        t0_2024 = _param(self.params, slug, "joint_pace", "2024", "t0_s")
        if t0_2024 is None or slug not in self.t1:
            return None
        delta = self.t1[slug]["delta_lap_s"] + self.t3.get(slug, {}).get("static_mass_delta_s", 0.0)
        return float(t0_2024) + delta

    def _base_t0(self, slug: str) -> float | None:
        """The 2026 base pace under real-beats-transform precedence."""
        real = _param(self.params, slug, "joint_pace", "2026", "t0_s")
        if real is not None:
            return float(real)
        return self._transform_t0(slug)

    def transforms(self) -> dict:
        out = {"globals": {}, "circuits": {}}
        if self.exponent is not None:
            origin = AERO_NB + (" — prior fallback (thin/implausible sample), stylised"
                                if self.exponent.fallback else " — global fit over both-era apexes")
            out["globals"]["corner_speed_exponent"] = (round(self.exponent.exponent, 4), origin)
        if self.overtake is not None:
            out["globals"]["overtaking"] = {
                "beta_pace": (round(self.overtake.beta_pace, 4), OVERTAKE_NB),
                "shift_2026_logit": (round(self.overtake.shift_2026, 4),
                                     OVERTAKE_NB + " — 2026 pass-rate shift vs 2024"),
                "n_events": (self.overtake.n_events, OVERTAKE_NB),
            }
        if self.t4:
            c_lc_median = float(np.median([v["c_lc_s_per_mj"] for v in self.t4.values()]))
            out["globals"]["c_lc_median_s_per_mj"] = (
                round(c_lc_median, 4),
                ENERGY_NB + " — cross-circuit median, mirrored to physics_2026.yaml")
        if self.c_global is not None:
            out["globals"]["c_global_residual_s"] = (round(self.c_global, 4), RESIDUAL_NB)

        for slug in self._slugs():
            circuit = {}
            self._put_base(circuit, slug)
            if "base" not in circuit:
                # no real fit, no transform, no donor — insufficient data to place
                # this circuit in 2026 (E-13 spirit); emit nothing rather than a
                # partial circuit F05 cannot use
                log.info("transforms: %s has no base pace, skipped (insufficient data)", slug)
                continue
            self._put_t1(circuit, slug)
            self._put_t4(circuit, slug)
            self._put_t3(circuit, slug)
            self._put_t8(circuit, slug)
            out["circuits"][slug] = circuit
        return out

    def _put_base(self, circuit: dict, slug: str) -> None:
        real = _param(self.params, slug, "joint_pace", "2026", "t0_s")
        t0 = self._base_t0(slug)
        if t0 is None:
            t0, source = self._donor_base(slug)
            if t0 is None:
                return
        elif real is not None:
            source = "real 2026 fit"
        else:
            source = "transform (T1+T2+T3)"
        circuit["base"] = {
            "t0_2026_s": (round(t0, 3), POINTMASS_NB + f" — {source}"),
            "source": (source, POINTMASS_NB),
        }

    def _donor_base(self, slug: str):
        assignments = self.params.get("clusters", {}).get("assignments", {})
        if slug not in assignments:
            return None, None
        label = assignments[slug]
        mates = [m for m, lab in assignments.items()
                 if lab == label and m in self.t1 and m != slug]
        t0_2024 = _param(self.params, slug, "joint_pace", "2024", "t0_s")
        if not mates or t0_2024 is None:
            return None, None
        delta = float(np.mean([self.t1[m]["delta_lap_s"] for m in mates]))
        return float(t0_2024) + delta, f"donor cluster ({','.join(sorted(mates))})"

    def _put_t1(self, circuit: dict, slug: str) -> None:
        if slug not in self.t1:
            return
        p = self.t1[slug]
        circuit["t1_powertrain"] = {
            "full_throttle_s": (round(p["full_throttle_s"], 3), POINTMASS_NB),
            "top_speed_kmh": (round(p["top_speed_kmh"], 2), POINTMASS_NB),
            "e_dep_mj": (round(p["e_dep_mj"], 4), POINTMASS_NB),
            "delta_lap_s": (round(p["delta_lap_s"], 4), POINTMASS_NB),
            "effective_ok": (bool(self.effective[slug].ok), POINTMASS_NB + " — self-check gate"),
        }

    def _put_t4(self, circuit: dict, slug: str) -> None:
        if slug not in self.t4:
            return
        b = self.t4[slug]["budget"]
        circuit["t4_energy"] = {
            "h_max_mj": (b.h_max_mj, "sourced circuits.yaml (AR-05, E-02)"),
            "e_dep_mj": (round(b.e_dep_mj, 4), ENERGY_NB),
            "harvest_braking_mj": (round(b.harvest_braking_mj, 4), ENERGY_NB),
            "harvest_clipping_mj": (round(b.harvest_clipping_mj, 4), ENERGY_NB),
            "supply_mj": (round(b.supply_mj, 4), ENERGY_NB),
            "deficit_mj": (round(b.deficit_mj, 4), ENERGY_NB + " — derate deficit (F-02/F-04)"),
            "c_lc_s_per_mj": (round(self.t4[slug]["c_lc_s_per_mj"], 4), ENERGY_NB),
        }

    def _put_t3(self, circuit: dict, slug: str) -> None:
        if slug not in self.t3:
            return
        t = self.t3[slug]
        # AR-10 verified 16 Jul (INDEX decisions log), so the mass delta is grade A
        circuit["t3_mass_fuel"] = {
            "static_mass_delta_s": (round(t["static_mass_delta_s"], 4),
                                   POINTMASS_NB + " — k_m*(dm) (T3, E-10)"),
            "avg_fuel_kg_2026": (round(t["avg_fuel_kg_2026"], 3),
                                POINTMASS_NB + " — half the 70 kg allowance (T6, AR-10)"),
            "k_m_s_per_kg": (round(t["k_m_s_per_kg"], 6), POINTMASS_NB),
        }

    def _put_t8(self, circuit: dict, slug: str) -> None:
        if slug in self.residual:
            circuit["t8_residual"] = {
                "c_circuit_s": (round(self.residual[slug], 4),
                                RESIDUAL_NB + " — real 2026 minus model median"),
            }
        elif self.c_global is not None:
            circuit["t8_residual"] = {
                "c_circuit_s": (round(self.c_global, 4),
                                RESIDUAL_NB + " — pooled c_global (no 2026 data)"),
            }

    def write_physics_2026_fitted(self, path: Path) -> None:
        if not self.t4:
            return
        c_lc = float(np.median([v["c_lc_s_per_mj"] for v in self.t4.values()]))
        c_atk = float(np.median([v["c_atk_s"] for v in self.t4.values()
                                 if v["c_atk_s"] is not None]))
        p_der = float(np.median([v["p_der_s_per_mj"] for v in self.t4.values()
                                 if v["p_der_s_per_mj"] is not None]))
        nb = "fitted: notebooks/fit_energy_budget.ipynb"
        # rewrite by key so a rerun is idempotent whether the value is still null
        # or an earlier run's number — the F02 make-fit-rerun discipline
        filled = [
            ("conserve_pace_cost_s_per_mj", round(c_lc, 4), "cross-circuit median c_lc (T4)"),
            ("attack_pace_gain_s", round(c_atk, 4), "override gain, longest straight (5.5.3)"),
            ("derate_penalty_s_per_mj", round(p_der, 4), "deploy-shortfall cost (5.5.3)"),
        ]
        text = path.read_text()
        for key, value, note in filled:
            pattern = rf"(?m)^  {key}:.*$"
            if not re.search(pattern, text):
                raise SystemExit(f"physics_2026.yaml has no '{key}' line to fill")
            replacement = f"  {key}: {value}  # {nb} — {note}"
            text = re.sub(pattern, lambda _, r=replacement: r, text)
        path.write_text(text)
        log.info("wrote c_lc=%.4f c_atk=%.4f p_der=%.4f to %s", c_lc, c_atk, p_der, path)


def _representative_trace(event_row, loader):
    """Fastest green accurate lap's telemetry, split into trace_ids (T1/T2 input)."""
    if event_row is None:
        return None
    try:
        car_data, laps = loader.load_car_data(
            int(event_row["season"]), int(event_row["round"]), "Race"
        )
    except Exception as err:
        log.warning("telemetry load failed for %s %s: %r",
                    event_row["season"], event_row["slug"], err)
        return None
    green = laps[
        laps["IsAccurate"].fillna(False).astype(bool)
        & laps["LapTime"].notna()
        & laps["LapStartTime"].notna()
        & laps["TrackStatus"].map(lambda s: set(str(s)) == {"1"})
    ]
    if green.empty:
        return None
    fastest = green.loc[green["LapTime"].idxmin()]
    driver_number = str(fastest["DriverNumber"])
    if driver_number not in car_data:
        return None
    gap_split_s = float(config.get(config.load("ingest"), "cleaning.telemetry_gap_split_s"))
    traced, _ = split_telemetry_gaps(car_data[driver_number], gap_split_s)
    window = (traced["Time"] >= fastest["LapStartTime"]) & (
        traced["Time"] < fastest["LapStartTime"] + fastest["LapTime"]
    )
    lap_trace = traced[window].reset_index(drop=True)
    return lap_trace if len(lap_trace) >= 2 else None


def _profile_2026(trace, car, *, exponent, taper, p_ice_2026, drag_scale, mass_2026,
                  downforce_ratio, throttle_full_pct):
    """Recompose the 2026 lap from the 2024 phases with 2026 power, drag and grip."""
    corner_speed_scale = downforce_ratio**exponent
    beta_2026 = car.beta_drag * drag_scale
    full_throttle_s = 0.0
    e_dep_mj = 0.0
    top_speed_kmh = 0.0
    delta_lap_s = 0.0
    longest_straight = None
    for phase in lap_phases(trace, throttle_full_pct=throttle_full_pct):
        if phase.kind == "throttle" and phase.dist_m > 0.0:
            v0_2026 = phase.v_start_kmh * corner_speed_scale
            run = pointmass.run_straight(
                v0_2026, phase.dist_m, mass_kg=mass_2026, p_base_kw=p_ice_2026,
                beta_drag=beta_2026, taper=taper,
            )
            full_throttle_s += run.time_s
            e_dep_mj += run.e_dep_mj
            top_speed_kmh = max(top_speed_kmh, run.v_end_kmh)
            delta_lap_s += run.time_s - (phase.t_end_s - phase.t_start_s)
            if longest_straight is None or phase.dist_m > longest_straight["dist_m"]:
                longest_straight = {
                    "v0_kmh": v0_2026, "dist_m": phase.dist_m, "beta_2026": beta_2026,
                }
        elif phase.kind != "throttle":
            # corner traversal time scales inversely with corner speed (T2)
            observed_s = phase.t_end_s - phase.t_start_s
            delta_lap_s += observed_s * (1.0 / corner_speed_scale - 1.0)
    return {
        "full_throttle_s": full_throttle_s,
        "e_dep_mj": e_dep_mj,
        "top_speed_kmh": top_speed_kmh,
        "delta_lap_s": delta_lap_s,
        "longest_straight": longest_straight,
    }


def _circuit_h_max(circuits_cfg: dict, slug: str) -> float:
    entry = circuits_cfg.get(slug)
    if entry is None or entry.get("h_max_mj") is None:
        raise SystemExit(
            f"circuits.yaml has no h_max_mj for '{slug}' — add the per-event cap (E-02)"
        )
    return float(entry["h_max_mj"])


def _param(params: dict, slug: str, block: str, era: str, key: str):
    # params_writer renders era keys unquoted, so yaml reloads "2024" as int 2024
    try:
        era_block = params["circuits"][slug][block]
    except (KeyError, TypeError):
        return None
    sub = era_block.get(int(era), era_block.get(era))
    return None if not isinstance(sub, dict) else sub.get(key)


