"""5.4.1 validation metrics — the numbers Chapter 6 reports per held-out circuit.

This module and heldout.py are the only ones allowed to read rounds 7+; every
other synth module refuses them (E-14). The metrics themselves are distribution
distances between the generator's Monte Carlo output and the real held-out
races: lap-time KS, stint-length EMD, pit delta, and event-rate band checks.

Run it: python -m senna.physics.synth.validate   (or `make synth-figures`)
"""

import argparse
import asyncio
import logging
from pathlib import Path

import numpy as np
import pandas as pd
from scipy import stats

from senna import config
from senna.data.db import database_url, engine_for
from senna.physics.fits.params_writer import render_params
from senna.physics.synth import heldout, montecarlo, plots

log = logging.getLogger(__name__)
SLICKS = ("SOFT", "MEDIUM", "HARD")
SUMMARY_HEADER = (
    "# SENNA — 5.4.1 sim-to-real validation summary (F03), held-out 2026 rounds.\n"
    "# Generated by senna.physics.synth.validate; the headline sim-to-real numbers.\n"
)


def ks_distance(sim_s: np.ndarray, real_s: np.ndarray) -> float:
    """Two-sample Kolmogorov-Smirnov statistic — max CDF gap (5.4.1, target < 0.15)."""
    sim_sorted = np.sort(np.asarray(sim_s, dtype=float))
    real_sorted = np.sort(np.asarray(real_s, dtype=float))
    grid = np.concatenate([sim_sorted, real_sorted])
    cdf_sim = np.searchsorted(sim_sorted, grid, side="right") / sim_sorted.size
    cdf_real = np.searchsorted(real_sorted, grid, side="right") / real_sorted.size
    return float(np.max(np.abs(cdf_sim - cdf_real)))


def stint_emd_laps(sim_lengths: np.ndarray, real_lengths: np.ndarray) -> float:
    """Earth-mover distance between stint-length histograms, in laps (5.4.1)."""
    return float(stats.wasserstein_distance(sim_lengths, real_lengths))


def pit_delta_within(sim_mean_s: float, real_mean_s: float, *, tolerance_s: float) -> bool:
    """Simulated pit delta within tolerance of the OpenF1 mean; boundary passes (5.4.1)."""
    return abs(sim_mean_s - real_mean_s) <= tolerance_s


def rate_within_band(rate: float, band_low: float, band_high: float) -> bool:
    """Event rate inside the fitted Wilson band; edges inclusive (E-03)."""
    return band_low <= rate <= band_high


async def run_validation(args: argparse.Namespace) -> dict:
    synth_cfg = config.load("synth")
    split = config.load("data_split")
    transforms = config.load("transforms")
    params = config.load("physics_params")
    validation_from = int(config.get(split, "validation_rounds_from"))
    ks_target = float(config.get(synth_cfg, "validation.ks_target"))
    pit_tol = float(config.get(synth_cfg, "validation.pit_tolerance_s"))
    seed = int(config.get(synth_cfg, "montecarlo.seed"))
    n_races = int(config.get(synth_cfg, "montecarlo.n_races"))
    grid_size = int(config.get(config.load("physics_2026"), "sporting.grid_size"))
    jitter = float(config.get(synth_cfg, "montecarlo.stint_jitter_laps_sigma"))

    engine = engine_for(database_url())
    try:
        async with engine.connect() as conn:
            real_laps = await heldout.held_out_race_laps(conn, validation_from)
            real_pits = await heldout.held_out_pit_stops(conn, validation_from)
    finally:
        await engine.dispose()

    summary = {}
    for slug in sorted(real_laps["slug"].unique()) if not real_laps.empty else []:
        real = real_laps[real_laps["slug"] == slug]
        n_laps = int(real["lap_number"].max())  # the real held-out race distance
        spec = _mc_spec(slug, transforms, params, n_laps)
        if spec is None:
            log.info("validate %s: no transform/fit inputs, skipped", slug)
            continue
        real_green = real[
            real["is_green"].fillna(False).astype(bool)
            & real["is_accurate"].fillna(False).astype(bool)
        ]["lap_time_s"].to_numpy(dtype=float)
        if real_green.size < 2:
            continue
        draw = montecarlo.sample_races(spec, n_races=n_races, n_cars=grid_size, seed=seed,
                                       stint_jitter_laps_sigma=jitter)
        sim_green = draw[draw["is_green"]]["lap_time_s"].to_numpy()
        ks = ks_distance(sim_green, real_green)
        emd = _stint_emd(draw, real)
        pit_ok, sim_pit, real_pit = _pit_check(slug, spec, real_pits, pit_tol)
        deficit = _param(transforms, slug, "t4_energy", "deficit_mj")
        summary[slug] = {
            "lap_time_ks": (round(ks, 4), f"KS vs real held-out green laps; target < {ks_target}"),
            "ks_within_target": (bool(ks < ks_target), "5.4.1 target met"),
            "stint_emd_laps": (round(emd, 3), "earth-mover distance, sim vs real stint lengths"),
            "pit_delta_within_1s": (bool(pit_ok),
                                    f"|sim {sim_pit:.1f} - real {real_pit:.1f}| <= {pit_tol}"),
            "sim_minus_real_median_s": (
                round(float(np.median(sim_green) - np.median(real_green)), 3),
                "headline sim-to-real lap-time offset"),
            "derate_deficit_mj": (round(float(deficit), 3) if deficit is not None else 0.0,
                                  "T4 energy shortfall — higher means more straight-line derate"),
        }
        _plot_circuit(slug, sim_green, real_green, ks)
        log.info("validate %s: KS=%.3f (target %.2f) EMD=%.2f pit_ok=%s",
                 slug, ks, ks_target, emd, pit_ok)

    args.summary_out.parent.mkdir(parents=True, exist_ok=True)
    args.summary_out.write_text(
        render_params(summary, generated_at=f"held-out from round {validation_from}",
                      header=SUMMARY_HEADER)
    )
    log.info("wrote %s (%d held-out circuits)", args.summary_out, len(summary))
    return summary


def _mc_spec(slug: str, transforms: dict, params: dict, n_laps: int) -> dict | None:
    base = _param(transforms, slug, "base", "t0_2026_s")
    circuit = params.get("circuits", {}).get(slug, {})
    joint = circuit.get("joint_pace", {})
    era = joint.get(2026) or joint.get(2024)  # yaml reloads era keys as ints
    deg_block = circuit.get("degradation", {})
    deg = deg_block.get(2026) or deg_block.get(2024)
    hazards = circuit.get("hazards")
    pit = circuit.get("pit_loss")
    globals_ = params.get("globals", {})
    status = globals_.get("status_pace_2026") or globals_.get("status_pace_2024")
    if None in (base, era, deg, hazards, pit, status):
        return None
    offsets = era["compound_offsets_s"]
    degradation = {
        c: {"a": float(deg[c]["a"]), "b": float(deg[c]["b"]),
            "offset_s": float(offsets.get(c, 0.0))}
        for c in SLICKS if c in deg
    }
    if len(degradation) < 2:
        return None
    residual = _param(transforms, slug, "t8_residual", "c_circuit_s") or 0.0
    return {
        "n_laps": n_laps,
        "t0_s": float(base) + float(residual),
        "sigma_driver_s": float(era["sigma_driver_s"]),
        "sigma_lap_s": float(era.get("s_ref_s", 1.0)),
        "k_m_s_per_kg": _f(era["k_m_s_per_kg"]),
        "race_fuel_kg": float(config.get(config.load("physics_2026"), "mass.race_fuel_kg")),
        "sc_burn_factor": float(config.get(config.load("fits"), "fuel.sc_burn_factor")),
        "evolution_s_per_lap": _f(era["evolution_s_per_lap"]),
        "degradation": degradation,
        "hazards": {"sc_lambda_per_lap": float(hazards["sc"]["lambda_per_lap"]),
                    "vsc_lambda_per_lap": float(hazards["vsc"]["lambda_per_lap"])},
        "status_mult": {"sc": float(status["sc_lap_time_mult"]),
                        "vsc": float(status["vsc_lap_time_mult"])},
        "pit_loss_mean_s": float(pit["mean_s"]),
        "pit_loss_sigma_s": float(pit["sigma_s"]),
    }


def _f(value) -> float:
    return 0.0 if value is None else float(value)


def _stint_emd(draw: pd.DataFrame, real: pd.DataFrame) -> float:
    """EMD between per-driver stint-length histograms, sim vs real (5.4.1)."""
    # a stint runs from a fresh tyre (age 0) to the next; count laps per stint on
    # both sides at the (unit, stint) grain — never pooling drivers into one bucket
    stint_id = (draw["tyre_age"] == 0).groupby([draw["race"], draw["car"]]).cumsum()
    sim_stint = draw.assign(stint=stint_id)
    sim_lengths = sim_stint.groupby(["race", "car", "stint"]).size().to_numpy(dtype=float)
    real_lengths = (
        real.groupby(["round", "driver", "stint"]).size().to_numpy(dtype=float)
    )
    if sim_lengths.size == 0 or real_lengths.size == 0:
        return 0.0
    return stint_emd_laps(sim_lengths, real_lengths)


def _pit_check(slug: str, spec: dict, real_pits: pd.DataFrame, tolerance_s: float):
    # caveat: sim_pit is the F02-fitted net pit loss and real is the OpenF1
    # stationary duration; they are close in this data but not the same quantity,
    # so read a near-miss here as a definition gap, not necessarily a model error
    sim_pit = spec["pit_loss_mean_s"]
    circuit_pits = (
        real_pits[real_pits["slug"] == slug]["pit_duration_s"].dropna()
        if not real_pits.empty else pd.Series(dtype=float)
    )
    real_pit = float(circuit_pits.mean()) if not circuit_pits.empty else sim_pit
    return pit_delta_within(sim_pit, real_pit, tolerance_s=tolerance_s), sim_pit, real_pit


def _plot_circuit(slug: str, sim_green: np.ndarray, real_green: np.ndarray, ks: float) -> None:
    fig = plots.lap_time_ecdf(sim_green, real_green, ks=ks, title=slug)
    plots.save_figure(fig, "validation", slug)


def _param(transforms: dict, slug: str, block: str, key: str):
    try:
        return transforms["circuits"][slug][block][key]
    except (KeyError, TypeError):
        return None


def _cli() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description="SENNA 5.4.1 sim-to-real validation (F03)")
    parser.add_argument("--summary-out", type=Path,
                        default=config.REPO_ROOT / "docs" / "synth" / "validation_summary.yaml")
    return parser


def main(argv: list[str] | None = None) -> None:
    logging.basicConfig(level=logging.INFO, format="%(levelname)s %(name)s: %(message)s")
    asyncio.run(run_validation(_cli().parse_args(argv)))


if __name__ == "__main__":
    main()
