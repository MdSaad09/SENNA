"""`make report` — regenerate the Chapter 7 tables and figures from the committed store.

A pure function of docs/results/F14/store and configs/eval.yaml: no environment, no torch,
no database. That is what makes the claim "deterministic given the run store" checkable
rather than asserted — a marker with a clone and no GPU can reproduce the tables, and a
rerun that changed nothing produces identical bytes.

Every metric row carries its target, its verdict and its gaming note. The notes are not
decoration: 5.12's whole design is that a number without its failure mode is not evidence,
so they come out of the config verbatim rather than being paraphrased here.
"""

import argparse
import logging
import textwrap
from pathlib import Path

from senna import config
from senna.eval.store import read_metric

log = logging.getLogger(__name__)

_HEADER = """# F14 — the evaluation suite: M1-M11 with confidence intervals

Generated by `make report` from the committed store in `docs/results/F14/store`, which
`make suite` writes. This document is regenerated, never hand-edited: every number below
traces to a stored row carrying the model version, the config hash, the seed manifest
fingerprint and the commit that produced it.

Evaluation runs on held-out ground throughout — the reserved Stage C test seeds (24
circuits x 20, `configs/seeds.yaml`) and the held-out rival band (E-06). Neither is
reachable from training: the seed loader refuses every consumer but this suite, and
`stage_venv` raises on any band but the train one.
"""

_METHOD = """
## How to read these numbers

Pairing is on event traces, not on seeds. The environment consumes randomness in a
policy-dependent way — a tyre only rolls for failure past its cliff, a stop only draws
service time when it happens — so two policies handed the same seed diverge in their events
after the first different stop. Every paired comparison here records one leg's race and
replays both legs through it, which is what makes "identical draws" true rather than
approximately true.

M3, M5 and M6 all ask counterfactual questions of a race that already happened, and all
three answer them on the deterministic twin of that race. The twin freezes the events and
switches off pace noise, so an alternative is priced by its decision rather than by the
luck it happened to meet.
"""


def build_report(store_dir=None, *, configs_dir=None, figures: bool = True) -> str:
    cfg = config.load("eval", configs_dir)
    store_dir = Path(store_dir) if store_dir else config.REPO_ROOT / cfg["store"]["committed_dir"]

    rows, envelope = [], None
    for name, builder in _ROWS:
        payload = _read(store_dir, name)
        if payload is None:
            continue
        envelope = envelope or payload["envelope"]
        rows.extend(builder(payload["payload"], cfg))

    body = [_HEADER, _provenance(envelope, store_dir), _METHOD, _table(rows), _notes(rows, cfg)]
    if figures:
        written = _figures(store_dir, config.REPO_ROOT / "docs/results/F14/figures")
        if written:
            body.append(_figure_section(written))
    body.append(_reproducing())
    return "\n".join(body)


def _read(store_dir, name):
    path = Path(store_dir) / f"{name}.json"
    return read_metric(store_dir, name) if path.exists() else None


def _provenance(envelope, store_dir) -> str:
    if envelope is None:
        return "\nNo stored metrics found — run `make suite` first.\n"
    versions = ", ".join(f"{k} `{v}`" for k, v in sorted(envelope["model_versions"].items()))
    return textwrap.dedent(f"""
        ## Provenance

        | | |
        |---|---|
        | Models | {versions} |
        | Env config hash | `{envelope['config_hash'][:12]}` |
        | Seed manifest | `{envelope['seeds_fingerprint'][:12]}` |
        | Commit | `{envelope['git_commit'][:12]}` |
        | Store | `{Path(store_dir).relative_to(config.REPO_ROOT)}` |
        """)


def _table(rows) -> str:
    lines = [
        "\n## The metric table (5.12)\n",
        "| Metric | Value | 95% CI | Target | Verdict |",
        "|---|---|---|---|---|",
    ]
    for row in rows:
        lines.append(
            f"| {row['id']} {row['name']} | {row['value']} | {row['ci']} | "
            f"{row['target']} | {row['verdict']} |"
        )
    return "\n".join(lines) + "\n"


def _notes(rows, cfg) -> str:
    lines = ["\n## How each metric can be gamed or misread\n"]
    for key in sorted({row["block"] for row in rows}):
        note = cfg.get(key, {}).get("gaming_note")
        if note:
            lines.append(f"**{key.upper()}.** {' '.join(note.split())}\n")
    return "\n".join(lines)


def _reproducing() -> str:
    return textwrap.dedent("""
        ## Reproducing this

            make suite            # rolls every battery, rewrites the committed store
            make report           # regenerates this document and its figures

        `make report` reads only the committed store, so it needs no model, no database and
        no GPU. `make suite` needs the frozen triplet in `models/headline` and, for the
        era-matched counterfactuals, `models/era2024` from `make finetune`.

        A retrain invalidates every number here by construction (E-15): the store's rows
        carry the model version they were produced against, and a new checkpoint means a
        new suite run.
        """)


def _fmt(value, digits=3) -> str:
    if value is None:
        return "n/a"
    if isinstance(value, float):
        return "undefined" if value != value else f"{value:.{digits}f}"
    return str(value)


def _verdict(met) -> str:
    return "met" if met else "**miss**"


def _m1(payload, cfg):
    return [{
        "id": "M1", "name": "paired position delta", "block": "m1",
        "value": f"{_fmt(payload['mean_delta'])} places over {payload['n']} pairs",
        "ci": f"[{_fmt(payload['ci_low'])}, {_fmt(payload['ci_high'])}]",
        "target": f">= +{_fmt(payload['target'], 1)}, CI excluding 0",
        "verdict": _verdict(payload["met"]),
    }]


def _m3(payload, cfg):
    time = payload["time_regret_s"]
    return [{
        "id": "M3", "name": "oracle regret", "block": "m3",
        "value": (f"median {_fmt(time['median'], 2)} s "
                  f"(mean {_fmt(time['mean'], 2)} s, {payload['n_races']} races)"),
        "ci": (f"p05 {_fmt(time['quantiles'].get('0.05'), 2)} / "
               f"p95 {_fmt(time['quantiles'].get('0.95'), 2)}"),
        "target": "report distribution", "verdict": "reported",
    }]


def _m4(payload, cfg):
    return [{
        "id": "M4", "name": "energy utilisation", "block": "m4",
        "value": (f"{_fmt(payload['utilisation'])} deployed/E_dep, "
                  f"derates {_fmt(payload['derate_share'])} of green laps"),
        "ci": "-",
        "target": f">= {payload['target']} and derates <= {payload['max_derate_share']}",
        "verdict": _verdict(payload["met"]),
    }]


def _m5(payload, cfg):
    rows = []
    for status in ("sc", "vsc"):
        block = payload[status]
        rows.append({
            "id": "M5", "name": f"{status.upper()} decision quality", "block": "m5",
            "value": (f"precision {_fmt(block['precision'])}, recall {_fmt(block['recall'])} "
                      f"over {block['n_windows']} windows"),
            "ci": "-",
            "target": f"both >= {payload['targets']['precision']}",
            "verdict": _verdict(
                block["n_windows"] and block["precision"] == block["precision"]
                and block["precision"] >= payload["targets"]["precision"]
                and block["recall"] >= payload["targets"]["recall"]),
        })
    return rows


def _m6(payload, cfg):
    return [{
        "id": "M6", "name": "pit window accuracy", "block": "m6",
        "value": f"{_fmt(payload['share'])} of {payload['n_stops']} stops",
        "ci": f"[{_fmt(payload['ci_low'])}, {_fmt(payload['ci_high'])}]",
        "target": f">= {payload['target']}", "verdict": _verdict(payload["met"]),
    }]


def _m7(payload, cfg):
    return [{
        "id": "M7", "name": "strategy diversity", "block": "m7",
        "value": (f"{_fmt(payload['mean_entropy_nats'])} nats mean over "
                  f"{len(payload['per_circuit'])} circuits"),
        "ci": "-", "target": "report only", "verdict": "reported",
    }]


def _m9(payload, cfg):
    target = cfg["m9"]["max_failures_per_100"]
    return [{
        "id": "M9", "name": "tyre failure rate", "block": "m9",
        "value": (f"{_fmt(payload['failures_per_100'], 2)} per 100 races "
                  f"({payload['n_failures']}/{payload['n_races']})"),
        "ci": "-", "target": f"< {target}",
        "verdict": _verdict(payload["failures_per_100"] < target),
    }]


def _m10(payload, cfg):
    return [{
        "id": "M10", "name": "regulatory legality", "block": "m10",
        "value": (f"{payload['illegal_actions']} coerced actions, "
                  f"{payload['snapped']} snapped over {payload['n_races']} races"),
        "ci": "-", "target": "0 by construction",
        "verdict": _verdict(payload["clean"]),
    }]


def _m11(payload, cfg):
    return [{
        "id": "M11", "name": "luck share", "block": "m11",
        "value": f"{_fmt(payload['mean_share'])} of finishing-position variance",
        "ci": f"[{_fmt(payload['ci_low'])}, {_fmt(payload['ci_high'])}]",
        "target": "report only", "verdict": "reported",
    }]


_ROWS = (
    ("m1_pairs", _m1),
    ("m3_regret", _m3),
    ("m4_energy", _m4),
    ("m5_windows", _m5),
    ("m6_pits", _m6),
    ("m7_entropy", _m7),
    ("m9_failures", _m9),
    ("m10_legality", _m10),
    ("m11_decomposition", _m11),
)


def _figures(store_dir, figures_dir) -> list:
    import matplotlib

    matplotlib.use("Agg")  # no display in CI, and no backend-dependent rendering drift
    import matplotlib.pyplot as plt
    import numpy as np

    figures_dir.mkdir(parents=True, exist_ok=True)
    written = []

    pairs = _read(store_dir, "m1_pairs")
    if pairs:
        deltas = [row["baseline"] - row["agent"] for row in pairs["payload"]["per_pair"]]
        fig, ax = plt.subplots(figsize=(6, 3.2))
        ax.hist(deltas, bins=range(min(deltas) - 1, max(deltas) + 3), color="#3f6fb5")
        ax.axvline(0.0, color="#444", linewidth=1)
        ax.set_xlabel("position delta (positive = agent ahead)")
        ax.set_ylabel("paired races")
        ax.set_title("M1 paired position delta")
        written.append(_save(fig, figures_dir / "m1_delta_hist.png"))

    regret = _read(store_dir, "m3_regret")
    if regret and regret["payload"]["per_race"]:
        times = np.sort([row["time_regret_s"] for row in regret["payload"]["per_race"]])
        fig, ax = plt.subplots(figsize=(6, 3.2))
        ax.step(times, np.arange(1, times.size + 1) / times.size, color="#b5533f")
        ax.axvline(0.0, color="#444", linewidth=1)
        ax.set_xlabel("time regret vs the oracle (s)")
        ax.set_ylabel("cumulative share of races")
        ax.set_title("M3 oracle regret")
        written.append(_save(fig, figures_dir / "m3_regret_ecdf.png"))

    luck = _read(store_dir, "m11_decomposition")
    if luck:
        blocks = luck["payload"]["per_circuit"]
        names = sorted(blocks)
        shares = [blocks[name]["share"] for name in names]
        fig, ax = plt.subplots(figsize=(6, max(2.5, 0.22 * len(names))))
        ax.barh(names, shares, color="#4f8a5b")
        ax.set_xlim(0, 1)
        ax.set_xlabel("share of finishing-position variance from the event draw")
        ax.set_title("M11 luck share")
        written.append(_save(fig, figures_dir / "m11_variance.png"))

    return written


def _save(fig, path) -> Path:
    fig.tight_layout()
    # metadata off: matplotlib stamps a creation date into the PNG otherwise, and the
    # committed figure would differ on every run for no reason
    fig.savefig(path, dpi=140, metadata={"Software": None})
    fig.clf()
    return path


def _figure_section(written) -> str:
    lines = ["\n## Figures\n"]
    for path in written:
        rel = Path(path).relative_to(config.REPO_ROOT / "docs/results")
        lines.append(f"![{Path(path).stem}]({rel})\n")
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description="regenerate the Chapter 7 tables (5.12)")
    parser.add_argument("--store", default=None)
    parser.add_argument("--out", default=None)
    parser.add_argument("--no-figures", action="store_true")
    args = parser.parse_args()

    logging.basicConfig(level=logging.INFO, format="%(message)s")
    out = Path(args.out) if args.out else config.REPO_ROOT / "docs/results/F14-evaluation.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(build_report(args.store, figures=not args.no_figures))
    log.info("wrote %s", out)


if __name__ == "__main__":
    main()
