"""The frozen data snapshot (A-09): pg_dump the ingested store once, record what was
dumped, and let an examiner verify the release asset without connecting to anything.

The dump itself is gitignored — hundreds of megabytes belong on the GitHub release,
not in history — and data/snapshot/MANIFEST.md is committed in its place: the file
name, the sha256, the exact size and per-table row counts. `make snapshot` writes
both; `make restore` loads a dump back, and only into a disposable database — restore
is the db-wipe incident with a new spelling, so require_disposable fires before any
subprocess exists to do damage.
"""

import subprocess
from pathlib import Path
from urllib.parse import urlparse

from senna.data.db import require_disposable


def _libpq_url(url: str) -> str:
    """pg_dump speaks libpq, not SQLAlchemy: strip the +asyncpg driver marker."""
    return url.replace("+asyncpg", "")


def row_counts(url: str) -> dict:
    """Exact per-table counts, straight count(*) — the manifest is a verification
    artifact, so an estimate from pg_stat would defeat its purpose."""
    import asyncio

    from sqlalchemy import text
    from sqlalchemy.ext.asyncio import create_async_engine

    async def count() -> dict:
        engine = create_async_engine(url if "+asyncpg" in url
                                     else url.replace("postgresql://",
                                                      "postgresql+asyncpg://"))
        counts = {}
        try:
            async with engine.connect() as conn:
                tables = (await conn.execute(text(
                    "select tablename from pg_tables where schemaname = 'public' "
                    "order by tablename"
                ))).scalars().all()
                for table in tables:
                    counts[table] = (await conn.execute(
                        text(f'select count(*) from "{table}"')  # noqa: S608 — pg_tables names, not user input
                    )).scalar_one()
        finally:
            await engine.dispose()
        return counts

    return asyncio.run(count())


def dump_snapshot(url: str, dest_dir) -> Path:
    """One custom-format archive (compressed, pg_restore-able) named after the database
    and the day. Reads only — the guard belongs on restore, not here."""
    from datetime import UTC, datetime

    dest_dir = Path(dest_dir)
    dest_dir.mkdir(parents=True, exist_ok=True)
    database = urlparse(_libpq_url(url)).path.lstrip("/") or "senna"
    dump_path = dest_dir / f"{database}-{datetime.now(UTC):%Y%m%d}.dump"
    subprocess.run(
        ["pg_dump", "--format=custom", "--no-owner", "--no-privileges",
         f"--file={dump_path}", _libpq_url(url)],
        check=True,
    )
    return dump_path


def restore(dump_path, url: str) -> None:
    """Load a dump into a disposable database. --clean --if-exists mirrors what the
    round-trip needs (drop what is there, recreate from the archive); the guard runs
    first because that drop is exactly the destructive step it exists to gate."""
    require_disposable(url)
    subprocess.run(
        ["pg_restore", "--clean", "--if-exists", "--no-owner", "--no-privileges",
         f"--dbname={_libpq_url(url)}", str(dump_path)],
        check=True,
    )


def write_manifest(*, dump_name: str, sha256: str, size_bytes: int,
                   row_counts: dict) -> str:
    """The committed record of the frozen snapshot — everything needed to verify the
    release asset offline. Regenerated by `make snapshot`, never hand-edited."""
    tables = "\n".join(f"| {table} | {count} |"
                       for table, count in sorted(row_counts.items()))
    return (
        "# Frozen data snapshot (A-09)\n"
        "\n"
        "Written by `make snapshot` (senna/data/snapshot.py). The dump itself is\n"
        "gitignored and rides the tagged GitHub release as an asset; this manifest is\n"
        "the committed half — verify a downloaded dump with `shasum -a 256` against\n"
        "the digest below, then `make restore` into a `*_test` database.\n"
        "\n"
        "| | |\n"
        "|---|---|\n"
        f"| Dump | `{dump_name}` |\n"
        f"| sha256 | `{sha256}` |\n"
        f"| Size (bytes) | {size_bytes} ({size_bytes / 1e6:.1f} MB) |\n"
        "\n"
        "| Table | Rows |\n"
        "|---|---|\n"
        f"{tables}\n"
    )


def main() -> None:
    import argparse
    import hashlib

    from senna import config
    from senna.data.db import database_url

    parser = argparse.ArgumentParser(description="freeze the ingested store (A-09)")
    parser.add_argument("--restore", type=Path, metavar="DUMP",
                        help="load DUMP instead of dumping; the target database "
                             "must pass require_disposable")
    args = parser.parse_args()

    url = database_url()
    if args.restore:
        restore(args.restore, url)
        print(f"restored {args.restore} into {urlparse(url).path.lstrip('/')}")
        return

    dest = config.REPO_ROOT / "data" / "snapshot"
    dump_path = dump_snapshot(url, dest)
    counts = row_counts(url)
    manifest = write_manifest(
        dump_name=dump_path.name,
        sha256=hashlib.sha256(dump_path.read_bytes()).hexdigest(),
        size_bytes=dump_path.stat().st_size,
        row_counts=counts,
    )
    (dest / "MANIFEST.md").write_text(manifest)
    print(f"dumped {dump_path} ({dump_path.stat().st_size / 1e6:.1f} MB, "
          f"{sum(counts.values())} rows) — MANIFEST.md updated, commit it")


if __name__ == "__main__":
    main()
